import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { findRepoRoot, type Db } from "@hci/db";
import { clubPageTexts, searchTexts, type TextHit } from "./snapshot-search";

/**
 * Leads for the editor's lifecycle list (ADR 0038/0039): sentences on a club's own pages
 * or a directory page about it that say the organization ended, was renamed, merged or
 * replaced. Nothing is recorded: an ending still needs an entry in `curated/lifecycle.ts`
 * with a verbatim quote, which `hci lifecycle` re-checks on the fetched page. A rename of
 * the same organization is a merge, not an ending. Read-only; no network.
 */

const ENDED =
  /\b(?:is|was|became|went|now)\s+(?:now\s+)?(?:defunct|disbanded|dissolved|inactive)\b|\bceased\s+(?:operations?|to\s+exist|publication|activities)\b|\bno\s+longer\s+(?:active|exists?|operat\w+|meets?|recogni[sz]ed)\b|\b(?:was|were)\s+(?:shut\s+down|discontinued|abolished)\b/i;
const RENAMED =
  /\b(?:formerly\s+(?:known\s+as|called)|renamed\s+(?:to|as|itself)|changed\s+(?:its|our)\s+name|(?:was|were)\s+replaced\s+by|merged\s+(?:with|into)|succeeded\s+by|reorgani[sz]ed\s+(?:as|into))\b/i;

export interface LifecycleLead {
  slug: string;
  name: string;
  kind: "ended" | "renamed_or_merged";
  url: string;
  excerpt: string;
}

/** Leads from page hits: each excerpt must itself carry the wording. PURE. */
export function lifecycleLeads(hits: readonly TextHit[], kind: LifecycleLead["kind"], re: RegExp): LifecycleLead[] {
  return hits.flatMap((h) =>
    h.excerpts
      .filter((e) => re.test(e))
      .map((excerpt) => ({ slug: h.page.slug, name: h.page.name, kind, url: h.page.url, excerpt })),
  );
}

export async function lifecycleCandidates(db: Db): Promise<{ leads: LifecycleLead[]; path: string }> {
  const { pages } = await clubPageTexts(db);
  const leads = [
    ...lifecycleLeads(searchTexts(pages, ENDED), "ended", ENDED),
    ...lifecycleLeads(searchTexts(pages, RENAMED), "renamed_or_merged", RENAMED),
  ];
  const lines = [
    "# Lifecycle leads",
    "",
    "Generated by `pnpm hci lifecycle --candidates` from stored pages (no network). Leads only:",
    "an ending is recorded by adding it to `packages/pipeline/src/curated/lifecycle.ts` with a",
    "verbatim quote and running `pnpm hci lifecycle`; a rename of the same club is a merge.",
    "Many hits are about something else (a past event, a partner group), so read each one.",
    "",
  ];
  for (const kind of ["ended", "renamed_or_merged"] as const) {
    const list = leads.filter((l) => l.kind === kind);
    lines.push(`## ${kind === "ended" ? "Says it ended" : "Renamed, merged or replaced"} (${list.length})`, "");
    for (const l of list) lines.push(`- **${l.name}** (\`${l.slug}\`) ${l.url}`, `  > ${l.excerpt}`);
    lines.push("");
  }
  const dir = join(findRepoRoot(), "data", "reports");
  mkdirSync(dir, { recursive: true });
  const path = join(dir, "lifecycle-candidates.md");
  writeFileSync(path, lines.join("\n"));
  return { leads, path };
}
