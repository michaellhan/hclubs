/** Query phrasings: "Harvard undergraduate X", "Harvard College X", "X at Harvard". */
export const SWEEP_TEMPLATES = ["Harvard undergraduate {t}", "Harvard College {t}", "{t} at Harvard"];

export function sweepQueries(
  topics: readonly string[] = SWEEP_TOPICS,
  templates: readonly string[] = SWEEP_TEMPLATES,
): string[] {
  return [...new Set(templates.flatMap((tpl) => topics.map((t) => tpl.replace("{t}", t))))];
}
